import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { InvalidInput, silent, type Log, type RoleHooks, type ServiceContext } from "@somework/agent-kit";
import { createGuard } from "./approvals.ts";
import { clusterChat, sameRepository } from "./chat.ts";
import type { Fetch } from "./http.ts";
import { loadSettings, type ClusterSettings } from "./settings.ts";
import { ciClientFor } from "./tools/ci.ts";
import { createClusterTools, type ClusterToolOptions } from "./tools/index.ts";

export interface ClusterHookOptions {
	settings: ClusterSettings;
	/** The credential for the organisation repository, when the service has one. */
	gitToken?: () => Promise<string>;
	/** The credential of each other repository, by its name. */
	extraGitTokens?: Readonly<Record<string, () => Promise<string>>>;
	/** Secret values the service holds besides the key and token files it reads itself (they are scrubbed from every tool answer). */
	extraSecrets?: () => string[];
	spawn?: ClusterToolOptions["spawn"];
	fetch?: Fetch;
	ci?: ClusterToolOptions["ci"];
	approved?: ClusterToolOptions["approved"];
	log?: Log;
	boundary?: () => string;
}

const readOrEmpty = (path: string): string => {
	try {
		return readFileSync(path, "utf8").trim();
	} catch {
		return "";
	}
};

/** Every secret the service can read: the ssh key of each host, the CI token and the repository credential. */
export function secretValues(settings: ClusterSettings, extra: readonly string[] = []): string[] {
	const files = [...settings.hosts.map((host) => join(settings.sshKeyDir, host.name)), ...settings.extraRepositories.map((repository) => repository.tokenFile), ...(settings.ci ? [settings.ci.tokenFile] : [])];
	return [...files.map(readOrEmpty), ...extra].filter((value) => value.length >= 8);
}

/**
 * The role's code on top of the kit's repository handler and conversations:
 *  - the host-side tools (`host_exec`, `git_push`, `ci_pipelines`, `ci_logs`, `deploy_status`) in the service process, and the guard that stops what
 *    the approval gate can only ask about (a push to a remote that is not the organisation's, a destructive command too long to confirm);
 *  - conversations: its standing orders, the larger change as the `cluster_change` job, the facts of the cluster and the read-only checkout;
 *  - `prepareInput` accepts the one configured repository and no other;
 *  - `pullRequest` says in the title and body that the change was made by an agent.
 */
export function createClusterHooks(options: ClusterHookOptions): RoleHooks {
	const { settings } = options;
	const log = options.log ?? silent;
	const secrets = () => secretValues(settings, options.extraSecrets?.() ?? []);
	const tools = createClusterTools({
		settings,
		secrets,
		log,
		...(options.spawn ? { spawn: options.spawn } : {}),
		...(options.fetch ? { fetch: options.fetch } : {}),
		...(options.gitToken ? { gitToken: options.gitToken } : {}),
		...(options.extraGitTokens ? { extraGitTokens: options.extraGitTokens } : {}),
		...(options.approved ? { approved: options.approved } : {}),
		...(options.boundary ? { boundary: options.boundary } : {}),
		ci: options.ci ?? ciClientFor(settings, options.fetch),
	});
	return {
		extensions: [tools.extension, createGuard(settings)],
		chat: clusterChat({ settings }),
		prepareInput(input) {
			const url = input?.repository?.url;
			if (!settings.repositoryUrl) throw new InvalidInput("this agent has no repository configured (CLUSTER_DEV_REPOSITORY)");
			if (typeof url !== "string" || !sameRepository(url, settings.repositoryUrl)) throw new InvalidInput("this agent only changes the repository it is configured for");
			return input;
		},
		pullRequest(input, { taskId }) {
			const subject = String(input?.instruction ?? "").split("\n")[0]!.trim().slice(0, 60) || "change";
			return {
				title: `cluster: ${subject}`,
				body: `${String(input?.instruction ?? "").slice(0, 6000)}\n\n---\nGenerated by an agent (SomeWork cluster-dev, task ${taskId}). **Nobody has reviewed it: review before merge.**`,
			};
		},
		readinessChecks: { ssh_keys: async () => settings.hosts.every((host) => existsSync(join(settings.sshKeyDir, host.name))) },
	};
}

/** For `runAgentService`: the hooks of the service being composed. Fails at startup when the deployment cannot work. */
export async function clusterDevHooksFor(context: ServiceContext): Promise<RoleHooks> {
	const settings = loadSettings(context.env);
	if (context.config.concurrency !== 1) throw new Error("the cluster development agent does one thing at a time: PI_CONCURRENCY must be 1");
	for (const host of settings.hosts) if (!existsSync(join(settings.sshKeyDir, host.name))) throw new Error(`the ssh key of the host ${host.name} is missing: ${join(settings.sshKeyDir, host.name)}`);
	if (settings.hosts.length > 0 && !existsSync(settings.sshKnownHosts)) throw new Error(`the known hosts file is missing: ${settings.sshKnownHosts}`);
	const gitToken = context.gitTokenSource ?? (context.gitToken ? async () => context.gitToken! : undefined);
	for (const repository of settings.extraRepositories) if (!existsSync(repository.tokenFile)) throw new Error(`the credential of the repository ${repository.name} is missing: ${repository.tokenFile}`);
	const extraGitTokens = Object.fromEntries(settings.extraRepositories.map((repository) => [repository.name, async () => readOrEmpty(repository.tokenFile)]));
	return createClusterHooks({ settings, ...(gitToken ? { gitToken } : {}), extraGitTokens, extraSecrets: () => (context.gitToken ? [context.gitToken] : []), log: context.log });
}
