import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, it } from "node:test";
import { InvalidInput, type ServiceContext } from "@somework/agent-kit";
import { CAPABILITY, clusterChangeTool, clusterChat, sameRepository } from "../src/chat.ts";
import { clusterDevHooksFor, createClusterHooks, secretValues } from "../src/hooks.ts";
import { profile } from "../src/profile.ts";
import { loadSettings } from "../src/settings.ts";
import { callTool, fakeSpawn, settingsFor, toolNamed } from "./support.ts";

const settings = settingsFor();

describe("the repository the agent accepts", () => {
	const hooks = createClusterHooks({ settings, spawn: fakeSpawn().spawn });
	const prepare = (url: unknown) => hooks.prepareInput!({ repository: { url, ref: "main" }, instruction: "x" }, { taskId: "t", log: () => undefined });

	it("is the configured one, however it is spelled", () => {
		for (const url of ["https://github.com/acme/somework", "https://github.com/acme/somework.git", "https://github.com/acme/somework/", "https://GitHub.com/Acme/SomeWork"]) assert.doesNotThrow(() => prepare(url), url);
		assert.equal(sameRepository("https://github.com/a/b.git", "https://github.com/a/b/"), true);
	});

	it("is no other repository, and no repository when none is configured", () => {
		for (const url of ["https://github.com/acme/other", "https://github.com/evil/somework", "git@github.com:acme/somework.git", "", undefined, 42]) assert.throws(() => prepare(url), InvalidInput, String(url));
		const unset = createClusterHooks({ settings: settingsFor({ CLUSTER_DEV_REPOSITORY: "" }) });
		assert.throws(() => unset.prepareInput!({ repository: { url: "https://github.com/acme/somework" } }, { taskId: "t", log: () => undefined }), /no repository configured/);
	});

	it("gets a pull request that says an agent made it and that nobody has reviewed it", () => {
		const pr = hooks.pullRequest!({ instruction: "fix the retry loop in the manager\nsecond line" }, { taskId: "task-1", instruction: "x" });
		assert.equal(pr.title, "cluster: fix the retry loop in the manager");
		assert.match(pr.body, /fix the retry loop in the manager\nsecond line/);
		assert.match(pr.body, /Generated by an agent \(SomeWork cluster-dev, task task-1\).*Nobody has reviewed it/);
	});
});

describe("the tools the hooks register", () => {
	it("are the five host-side tools, in one extension, and the guard", () => {
		const hooks = createClusterHooks({ settings });
		assert.equal(hooks.extensions?.length, 2);
		assert.deepEqual(hooks.extensions![0]!.tools!.map((tool) => tool.name), ["host_exec", "git_push", "ci_pipelines", "ci_logs", "deploy_status"]);
		assert.equal(hooks.extensions![1]!.name, "cluster-dev-guard");
		for (const name of hooks.extensions![0]!.tools!.map((tool) => tool.name)) assert.ok(profile.allowedTools!.includes(name), `${name} is offered to the model`);
	});

	it("scrub the key files and tokens the service holds from what host_exec prints", async () => {
		const dir = mkdtempSync(join(tmpdir(), "cluster-keys-"));
		mkdirSync(join(dir, "ssh"));
		const key = "-----BEGIN OPENSSH PRIVATE KEY-----\nAAAAB3NzaC1yc2EAAAADAQABAAABgQDexamplekeymaterial\n-----END OPENSSH PRIVATE KEY-----";
		writeFileSync(join(dir, "ssh", "agents"), key);
		writeFileSync(join(dir, "ci-token"), "ci-token-value-0123456789");
		const withFiles = settingsFor({ CLUSTER_DEV_SSH_KEY_DIR: join(dir, "ssh"), CI_TOKEN_FILE: join(dir, "ci-token") });
		assert.deepEqual(secretValues(withFiles, ["extra-secret-value"]).sort(), [key, "ci-token-value-0123456789", "extra-secret-value"].sort());
		const { spawn } = fakeSpawn({ stdout: "the ci token is ci-token-value-0123456789 and extra-secret-value" });
		const hooks = createClusterHooks({ settings: withFiles, spawn, extraSecrets: () => ["extra-secret-value"] });
		const { text } = await callTool(toolNamed(hooks.extensions![0]!, "host_exec"), { host: "agents", command: "hostname" });
		assert.ok(!text.includes("ci-token-value-0123456789"));
		assert.ok(!text.includes("extra-secret-value"));
	});

	it("ignore a key file that is missing instead of failing", () => {
		assert.deepEqual(secretValues(settingsFor({ CLUSTER_DEV_SSH_KEY_DIR: "/nonexistent" })), []);
	});
});

describe("conversations", () => {
	const chat = clusterChat({ settings });

	it("offer the larger change as one job tool, the facts of the cluster, and the checkout to copy", async () => {
		assert.deepEqual(chat.jobTools!.map((tool) => tool.name), ["cluster_change"]);
		assert.match(chat.instructions!, /cluster_change/);
		assert.match(chat.instructions!, /git_push/);
		assert.deepEqual(chat.checkout!(), { repoUrl: "https://github.com/acme/somework" });
		const facts = await chat.context!();
		assert.match(facts, /Repository: https:\/\/github.com\/acme\/somework; the only remote you push to is the organisation's \(org\)/);
		assert.match(facts, /Hosts for host_exec: agents, services, pve-host/);
		const withExtra = await clusterChat({ settings: settingsFor({ CLUSTER_DEV_EXTRA_REPOSITORIES: "somework=https://github.com/acme/public" }) }).context!();
		assert.match(withExtra, /you push to the organisation's remote \(org\) and to somework \(https:\/\/github.com\/acme\/public\), through git_push \(its repository argument names which one\)/);
		assert.match(facts, /Agents deploy_status reads: reviewer, developer/);
		assert.match(facts, /CI: Woodpecker, repository acme\/somework/);
		assert.equal(clusterChat({ settings: settingsFor({ CLUSTER_DEV_REPOSITORY: "" }) }).checkout, undefined);
		assert.match(await clusterChat({ settings: loadSettings({} as NodeJS.ProcessEnv) }).context!(), /Repository: not configured.*none configured.*CI: not configured/s);
	});

	it("plan a code.cluster job on the configured repository, and only for the card's capability", async () => {
		const tool = clusterChangeTool(settings);
		const planned = (await tool.plan({ instruction: "add a health check\nmore", ref: "main" })) as any;
		assert.deepEqual(planned, { capability: CAPABILITY, input: { repository: { url: "https://github.com/acme/somework", ref: "main" }, instruction: "add a health check\nmore" }, label: "change: add a health check" });
		assert.ok(profile.capabilities.some((entry) => entry.id === planned.capability.id && entry.version === planned.capability.version));
		assert.equal((await tool.plan({ instruction: "x" }) as any).input.repository.ref, "HEAD");
	});

	it("refuse an empty instruction, a bad ref, and any job when no repository is configured", async () => {
		const tool = clusterChangeTool(settings);
		assert.ok("refuse" in ((await tool.plan({ instruction: "   " })) as object));
		assert.ok("refuse" in ((await tool.plan({ instruction: "x", ref: "../../etc" })) as object));
		assert.ok("refuse" in ((await tool.plan({ instruction: "x", ref: "a b" })) as object));
		assert.ok("refuse" in ((await clusterChangeTool({}).plan({ instruction: "x" })) as object));
		const withRepo = (await tool.plan({ instruction: "x", repo: "https://github.com/evil/other" } as never)) as any;
		assert.equal(withRepo.input.repository.url, "https://github.com/acme/somework", "the model cannot name another repository");
	});
});

describe("starting the service", () => {
	const context = (env: Record<string, string>, over: Partial<ServiceContext["config"]> = {}): ServiceContext =>
		({ env: env as NodeJS.ProcessEnv, config: { concurrency: 1, ...over } as ServiceContext["config"], log: () => undefined, client: {} as never, gitToken: "ghs_abcdefghijklmnopqrstuvwxyz0123456789" }) as ServiceContext;

	it("builds the hooks for a deployment whose keys are in place", async () => {
		const dir = mkdtempSync(join(tmpdir(), "cluster-start-"));
		writeFileSync(join(dir, "agents"), "key");
		writeFileSync(join(dir, "known_hosts"), "agents ssh-ed25519 AAAA");
		const hooks = await clusterDevHooksFor(context({ CLUSTER_DEV_HOSTS: "agents=js@10.10.10.20", CLUSTER_DEV_SSH_KEY_DIR: dir, CLUSTER_DEV_REPOSITORY: "https://github.com/acme/somework" }));
		assert.ok(hooks.extensions && hooks.chat);
		assert.equal(await hooks.readinessChecks!.ssh_keys!(), true);
	});

	it("starts without hosts, for a first look at the logs", async () => {
		assert.ok(await clusterDevHooksFor(context({})));
	});

	it("fails at startup, not at the first command, when the setup cannot work", async () => {
		await assert.rejects(clusterDevHooksFor(context({}, { concurrency: 2 })), /PI_CONCURRENCY must be 1/);
		await assert.rejects(clusterDevHooksFor(context({ CLUSTER_DEV_HOSTS: "agents=js@10.10.10.20", CLUSTER_DEV_SSH_KEY_DIR: "/nonexistent" })), /ssh key of the host agents is missing/);
		const dir = mkdtempSync(join(tmpdir(), "cluster-start-"));
		writeFileSync(join(dir, "agents"), "key");
		await assert.rejects(clusterDevHooksFor(context({ CLUSTER_DEV_HOSTS: "agents=js@10.10.10.20", CLUSTER_DEV_SSH_KEY_DIR: dir })), /known hosts file is missing/);
		await assert.rejects(clusterDevHooksFor(context({ CLUSTER_DEV_GIT_REMOTE: "origin" })), /origin/);
		await assert.rejects(clusterDevHooksFor(context({ CI_URL: "https://ci", CI_REPO: "a/b" })), /CI_TOKEN_FILE/);
	});

	it("reports not ready when a host's key disappears", async () => {
		const dir = mkdtempSync(join(tmpdir(), "cluster-ready-"));
		writeFileSync(join(dir, "agents"), "key");
		const hooks = createClusterHooks({ settings: settingsFor({ CLUSTER_DEV_HOSTS: "agents=js@10.10.10.20,services=js@10.10.10.21", CLUSTER_DEV_SSH_KEY_DIR: dir }) });
		assert.equal(await hooks.readinessChecks!.ssh_keys!(), false);
	});
});
