#!/usr/bin/env python3
"""Creates (or updates, by uid) the SomeWork agents dashboard and its alert rules in Grafana. Standard library only; idempotent.

Everything is derived from the agents' structured logs that Alloy ships to Loki (events job_finished, job_failed, job_refused,
approval_requested, service_started, NATS fallback warnings), so it works for every agent role and host: docker agents, the Windows
agents' JSON files and the manager's journal. No notification target is configured (alert state is visible in Grafana only), like the
existing storage alert.

  python3 deploy/grafana/provision.py --url https://grafana.example --datasource loki-uid --folder "Agent Cluster" \\
      [--hub-url-file hub-url.txt --hub-ca-file ca.pem]   # also route the SomeWork alerts to the event hub (webhook contact point + policy route)

Authentication is whatever the Grafana front end gives the caller (here: the Tailscale identity); pass --token for a service account token.
"""
import argparse
import json
import pathlib
import urllib.error
import urllib.request

LABELS = "{{host}} {{container}} {{service_name}}"
SELECT_JOBS = '{event="job_finished"} | json | __error__=""'


def dashboard(ds):
    datasource = {"type": "loki", "uid": ds}
    panels = []

    def panel(title, expr, kind="timeseries", w=12, h=8, legend=LABELS, unit=None, bars=True, description=None):
        index = len(panels)
        p = {
            "id": len(panels) + 1, "title": title, "type": kind, "datasource": datasource,
            "gridPos": {"x": (index % 2) * 12, "y": (index // 2) * 8, "w": w, "h": h},
            "targets": [{"refId": "A", "expr": expr, "legendFormat": legend, "datasource": datasource, "queryType": "range"}],
            "fieldConfig": {"defaults": ({"unit": unit} if unit else {}), "overrides": []},
            "options": {},
        }
        if description:
            p["description"] = description
        if kind == "timeseries" and bars:
            p["fieldConfig"]["defaults"]["custom"] = {"drawStyle": "bars", "fillOpacity": 70, "stacking": {"mode": "normal"}}
        panels.append(p)

    panel("Jobs finished by status", f'sum by (status) (count_over_time({SELECT_JOBS} [$__auto]))', legend="{{status}}",
          description="One event per finished job (done, cancel_requested, lease_lost, ...), from every agent.")
    panel("Failures and refusals", 'sum by (event, host, container, service_name) (count_over_time({event=~"job_failed|job_refused"}[$__auto]))',
          legend="{{event}} " + LABELS, description="job_failed = infrastructure error (retryable); job_refused = budget or policy refusal.")
    panel("Model tokens", f'sum by (host, container, service_name) (sum_over_time({SELECT_JOBS} | unwrap totalTokens [$__auto]))', unit="short",
          description="Counted when a job finishes.")
    panel("Cost, USD", f'sum by (host, container, service_name) (sum_over_time({SELECT_JOBS} | unwrap costUsd [$__auto]))', unit="currencyUSD")
    panel("Job duration p95", f'quantile_over_time(0.95, {SELECT_JOBS} | unwrap durationMs [$__auto]) by (host, container, service_name)', unit="ms", bars=False)
    panel("Approvals requested", 'sum by (tool, container, service_name) (count_over_time({event="approval_requested"} | json | __error__="" [$__auto]))',
          legend="{{tool}} {{container}} {{service_name}}", description="Commands that waited for a human decision.")
    panel("Service starts (restart loop detector)", 'sum by (host, container, service_name) (count_over_time({event="service_started"}[$__auto]))',
          description="More than a few per hour for one agent means it is crash looping.")
    panel("NATS wake fallback", 'sum by (host, container, service_name) (count_over_time({event=~"NATS wake unavailable.*"}[$__auto]))',
          description="The agent could not use NATS and polled over HTTP meanwhile. Latency is higher but nothing is lost.")
    panels.append({
        "id": len(panels) + 1, "title": "Warnings and errors from the agents", "type": "logs", "datasource": datasource,
        "gridPos": {"x": 0, "y": ((len(panels) + 1) // 2) * 8, "w": 24, "h": 12},
        "targets": [
            {"refId": ref, "expr": '{cluster="agent-cluster", level=~"warn|warning|error", ' + selector + '}', "datasource": datasource, "queryType": "range"}
            for ref, selector in (("A", 'container=~"somework-.*"'), ("B", 'source="agent"'), ("C", 'service_name="pi-manager.service"'))
        ],
        "options": {"showTime": True, "wrapLogMessage": True, "enableLogDetails": True, "sortOrder": "Descending"},
    })
    return {
        "uid": "somework-agents", "title": "SomeWork Agents", "schemaVersion": 39, "version": 1, "refresh": "1m",
        "time": {"from": "now-24h", "to": "now"}, "tags": ["somework", "agents"], "panels": panels,
        "description": "Agent activity derived from structured logs. Generated by deploy/grafana/provision.py.",
    }


def rule(ds, folder, uid, title, expr, threshold, window_s, severity, summary, for_="0s", no_data="OK"):
    return {
        "uid": uid, "title": title, "ruleGroup": "SomeWork agents", "folderUID": folder, "orgID": 1,
        "condition": "B", "for": for_, "noDataState": no_data, "execErrState": "Error", "isPaused": False,
        "labels": {"severity": severity, "system": "somework"}, "annotations": {"summary": summary},
        "data": [
            {"refId": "A", "queryType": "instant", "relativeTimeRange": {"from": window_s, "to": 0}, "datasourceUid": ds,
             "model": {"datasource": {"type": "loki", "uid": ds}, "editorMode": "code", "expr": expr, "intervalMs": 1000, "maxDataPoints": 43200, "queryType": "instant", "refId": "A"}},
            {"refId": "B", "queryType": "", "relativeTimeRange": {"from": 0, "to": 0}, "datasourceUid": "__expr__",
             "model": {"datasource": {"type": "__expr__", "uid": "__expr__"}, "expression": f"$A > {threshold}", "intervalMs": 1000, "maxDataPoints": 43200, "refId": "B", "type": "math"}},
        ],
    }


def rules(ds, folder):
    return [
        rule(ds, folder, "somework-jobs-failing", "SomeWork jobs failing with infrastructure errors",
             'sum(count_over_time({event="job_failed"}[1h]))', 3, 3600, "ticket", "More than 3 agent jobs failed with errors in the last hour"),
        rule(ds, folder, "somework-budget-refusals", "SomeWork jobs refused on budget grounds",
             'sum(count_over_time({event="job_refused"}[1h]))', 0, 3600, "info", "An agent refused a job because its daily token budget is used up"),
        rule(ds, folder, "somework-token-burn", "SomeWork token burn",
             'sum(sum_over_time({event="job_finished"} | json | unwrap totalTokens | __error__="" [6h]))', 15000000, 21600, "ticket", "More than 15M model tokens in 6 hours (the busiest 6 hours of a week was 9.3M)"),
        rule(ds, folder, "somework-agent-restarts", "SomeWork agent restarting repeatedly",
             'max(sum by (host, container, service_name) (count_over_time({event="service_started"}[30m])))', 3, 1800, "page", "An agent started more than 3 times in 30 minutes (crash loop)"),
        rule(ds, folder, "somework-nats-fallback", "SomeWork agents lost their NATS wake",
             'sum(count_over_time({event=~"NATS wake unavailable.*"}[15m]))', 5, 900, "ticket", "Agents are polling over HTTP because NATS is unavailable or untrusted"),
        rule(ds, folder, "windows-alloy-errors", "Windows log shipper (Alloy) errors",
             'sum(count_over_time({host=~"admin-cloud-windows.*", service_name="Application"} |= "Alloy" |= "level=error" [30m]))', 5, 1800, "ticket",
             "Alloy on a Windows machine is logging errors (wrong identity, corrupt write-ahead log, rejected old entries)"),
        rule(ds, folder, "hypervisor-auth-failures", "Failed logins on the hypervisor web UI",
             'sum(count_over_time({service_name="pvedaemon.service"} |= "authentication failure" [1h]))', 50, 3600, "info",
             "Many failed logins against the hypervisor: the web UI and ssh are reachable from the internet"),
    ]


CONTACT_POINT_UID = "somework-hub"
ROUTE_MATCHER = ["system", "=", "somework"]


def contact_point(hub_url, ca_pem):
    settings = {"url": hub_url, "httpMethod": "POST", "maxAlerts": 20}
    if ca_pem:
        settings["tlsConfig"] = {"caCertificate": ca_pem, "insecureSkipVerify": False}
    return {"uid": CONTACT_POINT_UID, "name": CONTACT_POINT_UID, "type": "webhook", "settings": settings, "disableResolveMessage": False}


def with_hub_route(tree):
    """The notification policy tree with exactly one route sending the SomeWork alerts to the hub; everything else in the tree is kept."""
    routes = [r for r in (tree.get("routes") or []) if r.get("receiver") != CONTACT_POINT_UID]
    routes.append({"receiver": CONTACT_POINT_UID, "object_matchers": [ROUTE_MATCHER], "group_by": ["alertname"], "group_wait": "10s", "group_interval": "1m", "repeat_interval": "6h"})
    return {**tree, "routes": routes}


class Api:
    def __init__(self, base, token=None):
        self.base, self.token = base.rstrip("/"), token

    def call(self, method, path, body=None, headers=None):
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(self.base + path, data=data, method=method, headers={"Content-Type": "application/json", **({"Authorization": f"Bearer {self.token}"} if self.token else {}), **(headers or {})})
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                raw = r.read()
                return r.status, (json.loads(raw) if raw else None)
        except urllib.error.HTTPError as e:
            return e.code, e.read().decode()[:400]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", required=True)
    ap.add_argument("--datasource", required=True, help="uid of the Loki data source")
    ap.add_argument("--folder", default="Agent Cluster", help="title of an existing folder")
    ap.add_argument("--token")
    ap.add_argument("--hub-url-file", help="file holding the hub's internal listener URL for source grafana (it contains a secret); creates the webhook contact point and the policy route")
    ap.add_argument("--hub-ca-file", help="PEM file of the CA that signed the hub's TLS certificate (for https hub URLs)")
    a = ap.parse_args()
    api = Api(a.url, a.token)

    status, folders = api.call("GET", "/api/folders")
    folder = next((f["uid"] for f in folders if f["title"] == a.folder), None) if status == 200 else None
    if not folder:
        raise SystemExit(f"folder {a.folder!r} not found ({status})")

    status, body = api.call("POST", "/api/dashboards/db", {"dashboard": dashboard(a.datasource), "folderUid": folder, "overwrite": True, "message": "provision.py"})
    print("dashboard:", status, (body or {}).get("url") if isinstance(body, dict) else body)

    if a.hub_url_file:
        hub_url = pathlib.Path(a.hub_url_file).read_text().strip()
        ca_pem = pathlib.Path(a.hub_ca_file).read_text() if a.hub_ca_file else None
        headers = {"X-Disable-Provenance": "true"}
        cp = contact_point(hub_url, ca_pem)
        status, body = api.call("PUT", f"/api/v1/provisioning/contact-points/{CONTACT_POINT_UID}", cp, headers)
        if status == 404:
            status, body = api.call("POST", "/api/v1/provisioning/contact-points", cp, headers)
        print("contact point", CONTACT_POINT_UID, status, "" if status < 300 else body)
        status, tree = api.call("GET", "/api/v1/provisioning/policies")
        if status == 200:
            status, body = api.call("PUT", "/api/v1/provisioning/policies", with_hub_route(tree), headers)
            print("notification policy", status, "" if status < 300 else body)

    for r in rules(a.datasource, folder):
        headers = {"X-Disable-Provenance": "true"}
        status, body = api.call("PUT", f"/api/v1/provisioning/alert-rules/{r['uid']}", r, headers)
        if status == 404:
            status, body = api.call("POST", "/api/v1/provisioning/alert-rules", r, headers)
        print("alert", r["uid"], status, "" if status < 300 else body)


if __name__ == "__main__":
    main()
